CREATE TABLE payment_refunds (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_id BIGINT NOT NULL UNIQUE REFERENCES payments(id),
 order_id BIGINT NOT NULL,
 request_key VARCHAR(100) NOT NULL UNIQUE,
 operation_id VARCHAR(36) NOT NULL UNIQUE,
 amount NUMERIC(19,2) NOT NULL CHECK (amount>0),
 currency VARCHAR(3) NOT NULL,
 intent_id VARCHAR(100) NOT NULL,
 provider_refund_id VARCHAR(100) UNIQUE,
 status VARCHAR(24) NOT NULL CHECK (status IN ('REQUESTED','PENDING','SUCCEEDED','FAILED','REVIEW_REQUIRED')),
 automatic BOOLEAN NOT NULL,
 reason VARCHAR(80) NOT NULL,
 requested_by VARCHAR(255) NOT NULL,
 business_completed BOOLEAN NOT NULL DEFAULT FALSE,
 business_outcome VARCHAR(40),
 submitted_at TIMESTAMPTZ,
 next_attempt_at TIMESTAMPTZ,
 processing_token VARCHAR(36),
 processing_until TIMESTAMPTZ,
 attempts INTEGER NOT NULL DEFAULT 0,
 last_error VARCHAR(80),
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_refund_recovery ON payment_refunds (next_attempt_at,id);
